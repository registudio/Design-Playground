import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

/**
 * Turns the vendored cobe globe (and phenomenon, the WebGL helper it imports) into the
 * module the catalogue reads.
 *
 * The npm files stay byte-for-byte in vendor/cobe so an update is a plain copy and a
 * diff. What ships is the two bundled into one script that sets `window.createGlobe`,
 * minified, with both MIT notices at its head: every document that runs the globe
 * carries the library, so the notices travel with it.
 *
 * `cobeModule()` is exported for the test that holds the committed module to the
 * vendored files; run this file directly to rewrite it.
 */
const DIR = new URL('../vendor/cobe/', import.meta.url);
const OUT = new URL('../src/elements/cobe-source.ts', import.meta.url);

export async function cobeModule() {
  const cobe = (await readFile(new URL('LICENSE-cobe', DIR), 'utf8')).trim();
  const phenomenon = (await readFile(new URL('LICENSE-phenomenon', DIR), 'utf8')).trim();
  const notice = `/*! cobe 0.6.5 · https://github.com/shuding/cobe\n${cobe}\n\nphenomenon 1.6.0 · https://github.com/vaneenige/phenomenon\n${phenomenon}\n*/\n`;
  const result = await build({
    stdin: { contents: `import createGlobe from './cobe.esm.js';window.createGlobe=createGlobe;`, resolveDir: fileURLToPath(DIR), loader: 'js' },
    bundle: true,
    write: false,
    format: 'iife',
    minify: true,
    target: 'es2020',
    legalComments: 'none',
    alias: { phenomenon: fileURLToPath(new URL('phenomenon.mjs', DIR)) },
    logLevel: 'silent',
  });
  // `</script` is escaped by esbuild, which matters: this goes inside a <script>.
  const code = result.outputFiles[0].text.trim();
  return `// Generated by scripts/vendor-cobe.mjs from vendor/cobe. Do not edit.\n` +
    `export const COBE_SOURCE = ${JSON.stringify(notice + code)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(OUT, await cobeModule());
  console.log('wrote src/elements/cobe-source.ts');
}
