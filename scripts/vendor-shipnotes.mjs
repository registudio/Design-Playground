import { transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

/**
 * Turns the vendored Ship Notes components into the module the catalogue reads.
 *
 * The originals stay byte-for-byte in vendor/shipnotes-components so an update is a
 * plain copy and a diff. What ships is each file minified, with the MIT notice put back
 * at its head: every element document, card, export and review page carries the
 * component's script, so the notice travels with it wherever it goes.
 *
 * `shipnotesModule()` is exported for the test that holds the committed module to the
 * vendored files; run this file directly to rewrite it.
 */
export const SHIPNOTES_COMPONENTS = ['jelly-stack', 'project-stack', 'pull-lamp', 'signal-orb', 'speaking-orb', 'voice-orb'];
const DIR = new URL('../vendor/shipnotes-components/', import.meta.url);
const OUT = new URL('../src/elements/shipnotes-sources.ts', import.meta.url);

export async function shipnotesModule() {
  const licence = (await readFile(new URL('LICENSE', DIR), 'utf8')).trim();
  const notice = `/*! Ship Notes · https://github.com/aqualang89/shipnotes-components\n${licence}\n*/\n`;
  const entries = [];
  for (const name of SHIPNOTES_COMPONENTS) {
    const source = await readFile(new URL(`${name}.js`, DIR), 'utf8');
    // `</script` is escaped by esbuild, which matters: this goes inside a <script>.
    const { code } = await transform(source, { minify: true, target: 'es2022', legalComments: 'none' });
    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(notice + code.trim())},`);
  }
  return `// Generated by scripts/vendor-shipnotes.mjs from vendor/shipnotes-components. Do not edit.\n` +
    `export const SHIPNOTES_SOURCES = {\n${entries.join('\n')}\n} as const;\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(OUT, await shipnotesModule());
  console.log('wrote src/elements/shipnotes-sources.ts');
}
