import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

/**
 * Turns the vendored GradFlow shader and presets into the module the catalogue reads.
 *
 * The repository files stay byte-for-byte in vendor/gradflow so an update is a plain
 * copy and a diff. They are TypeScript modules exporting strings and objects, so they
 * are bundled and evaluated here, and their values written out as JSON beside the MIT
 * notice that every gradflow element ships at the head of its script.
 *
 * `gradflowModule()` is exported for the test that holds the committed module to the
 * vendored files; run this file directly to rewrite it.
 */
const DIR = new URL('../vendor/gradflow/', import.meta.url);
const OUT = new URL('../src/elements/gradflow-source.ts', import.meta.url);

export async function gradflowModule() {
  const licence = (await readFile(new URL('LICENSE', DIR), 'utf8')).trim();
  const notice = `/*! GradFlow · https://github.com/meerbahadin/gradflow\n${licence}\n*/`;
  const result = await build({
    stdin: {
      contents: `export { VERTEX_SHADER, FRAGMENT_SHADER } from './shader.ts';export { DEFAULT_CONFIG, GRADIENT_TYPE_NUMBER, PRESETS } from './gradients.ts';`,
      resolveDir: fileURLToPath(DIR),
      loader: 'ts',
    },
    bundle: true,
    write: false,
    format: 'esm',
    logLevel: 'silent',
  });
  const values = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
  const json = (value) => JSON.stringify(value);
  return `// Generated by scripts/vendor-gradflow.mjs from vendor/gradflow. Do not edit.\n` +
    `export const GRADFLOW_NOTICE = ${json(notice)};\n` +
    `export const GRADFLOW_VERTEX_SHADER = ${json(values.VERTEX_SHADER)};\n` +
    `export const GRADFLOW_FRAGMENT_SHADER = ${json(values.FRAGMENT_SHADER)};\n` +
    `export const GRADFLOW_TYPE_NUMBER = ${json(values.GRADIENT_TYPE_NUMBER)} as const;\n` +
    `export const GRADFLOW_DEFAULT_CONFIG = ${json(values.DEFAULT_CONFIG)} as const;\n` +
    `export const GRADFLOW_PRESETS = ${json(values.PRESETS)} as const;\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(OUT, await gradflowModule());
  console.log('wrote src/elements/gradflow-source.ts');
}
