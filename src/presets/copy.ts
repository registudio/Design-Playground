export type CopyPackId = keyof typeof SAMPLE_COPY;

/** The pack for a project's brand, with `{brand}` filled in. */
export function resolveCopy(id: CopyPackId | undefined, brand: string): SampleCopy {
  const copy = SAMPLE_COPY[id ?? "agency"] ?? AGENCY;
  const fill = (text: string) => text.replaceAll("{brand}", brand);
  return { ...copy, headline: fill(copy.headline), lede: fill(copy.lede) };
}
